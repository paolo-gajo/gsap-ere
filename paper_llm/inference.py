INLINE_MARKER_RE = re.compile(
    r"\[\[(?:(?P<close>/)(?P<close_id>e[1-9][0-9]*)|"
    r"(?P<open_id>e[1-9][0-9]*):(?P<label>[A-Za-z][A-Za-z0-9]*))\]\]"
)

CLOSE_PUNCTUATION = {",", ".", ";", ":", "!", "?", "%", ")", "]", "}", "'s"}
OPEN_PUNCTUATION = {"(", "[", "{"}
JOIN_BOTH_SIDES = {"-", "/", ":/"}


@dataclass(frozen=True)
class Entity:
    start: int
    end: int
    type: str


@dataclass(frozen=True)
class Relation:
    subject_start: int
    subject_end: int
    object_start: int
    object_end: int
    label: str


@dataclass(frozen=True)
class SentenceRecord:
    doc_id: str
    sentence_id: int
    tokens: tuple[str, ...]
    text: str
    entities: tuple[Entity, ...]
    relations: tuple[Relation, ...]

    @property
    def labels(self) -> frozenset[str]:
        return frozenset(entity.type for entity in self.entities)

    @property
    def key(self) -> str:
        return f"{self.doc_id}:{self.sentence_id}"


@dataclass(frozen=True)
class PairExample:
    record_index: int
    subject: Entity
    object: Entity
    label: str


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def detokenize_with_spans(
    tokens: Iterable[str],
) -> tuple[str, tuple[tuple[int, int], ...]]:
    rendered = ""
    spans = []
    previous = ""
    before_previous = ""
    quote_is_open = False
    for token in tokens:
        if not rendered:
            needs_space = False
        elif token == '"':
            needs_space = not quote_is_open and previous not in OPEN_PUNCTUATION
            quote_is_open = not quote_is_open
        elif previous == '"' and quote_is_open:
            needs_space = False
        elif previous == "," and before_previous.isdigit() and token.isdigit():
            needs_space = False
        elif previous == "∼" or (
            previous.isdigit()
            and len(token) > 1
            and token[0] in {"−", "+"}
            and token[1:].isdigit()
        ):
            needs_space = False
        elif token in CLOSE_PUNCTUATION or previous in OPEN_PUNCTUATION:
            needs_space = False
        elif token in JOIN_BOTH_SIDES or previous in JOIN_BOTH_SIDES:
            needs_space = False
        else:
            needs_space = True
        if needs_space:
            rendered += " "
        start = len(rendered)
        rendered += token
        spans.append((start, len(rendered)))
        before_previous = previous
        previous = token
    return rendered, tuple(spans)


def detokenize(tokens: Iterable[str]) -> str:
    return detokenize_with_spans(tokens)[0]


def collapse_entities(rows: list[list[Any]], offset: int, token_count: int) -> tuple[Entity, ...]:
    by_span: dict[tuple[int, int], set[str]] = {}
    for global_start, global_end, label in rows:
        start = global_start - offset
        end = global_end - offset
        if label not in ENTITY_ORDER or not 0 <= start <= end < token_count:
            continue
        by_span.setdefault((start, end), set()).add(label)
    result = []
    for (start, end), labels in by_span.items():
        label = min(labels, key=ENTITY_ORDER.__getitem__)
        result.append(Entity(start, end, label))
    return tuple(sorted(result, key=lambda entity: (entity.start, entity.end, ENTITY_ORDER[entity.type])))


def local_relations(rows: list[list[Any]], offset: int, token_count: int) -> tuple[Relation, ...]:
    result = []
    for global_ss, global_se, global_os, global_oe, label in rows:
        ss, se = global_ss - offset, global_se - offset
        os_, oe = global_os - offset, global_oe - offset
        if label not in RELATION_ORDER:
            continue
        if not (0 <= ss <= se < token_count and 0 <= os_ <= oe < token_count):
            continue
        result.append(Relation(ss, se, os_, oe, label))
    return tuple(result)


def load_records(path: Path, vocabulary: list[str]) -> list[SentenceRecord]:
    records: list[SentenceRecord] = []
    with path.open(encoding="utf-8") as stream:
        for line in stream:
            document = json.loads(line)
            offset = 0
            for sentence_id, (token_ids, ner_rows, relation_rows) in enumerate(
                zip(document["sentences"], document["ner"], document["relations"])
            ):
                tokens = tuple(vocabulary[token_id] for token_id in token_ids)
                records.append(
                    SentenceRecord(
                        doc_id=document["doc_id"],
                        sentence_id=sentence_id,
                        tokens=tokens,
                        text=detokenize(tokens),
                        entities=collapse_entities(ner_rows, offset, len(tokens)),
                        relations=local_relations(relation_rows, offset, len(tokens)),
                    )
                )
                offset += len(tokens)
    return records


def indexed_tokens(record: SentenceRecord) -> list[list[Any]]:
    return [[index, token] for index, token in enumerate(record.tokens)]


def format_full_article_context(records: list[SentenceRecord]) -> str:
    return "\n\n".join(
        f"[Sentence {record.sentence_id}] {record.text}"
        for record in sorted(records, key=lambda record: record.sentence_id)
    )


def entity_dict(entity: Entity, record: SentenceRecord) -> dict[str, Any]:
    return {
        "start": entity.start,
        "end": entity.end,
        "type": entity.type,
        "text": " ".join(record.tokens[entity.start : entity.end + 1]),
    }


def inline_annotated_sentence(record: SentenceRecord) -> str:
    text, token_spans = detokenize_with_spans(record.tokens)
    if "[[" in text or "]]" in text:
        raise RuntimeError(f"sentence {record.key} contains an inline marker delimiter")

    events: dict[int, list[tuple[tuple[int, int, int], str]]] = {}
    for index, entity in enumerate(record.entities, start=1):
        start = token_spans[entity.start][0]
        end = token_spans[entity.end][1]
        events.setdefault(start, []).append(
            ((1, -end, index), f"[[e{index}:{entity.type}]]")
        )
        events.setdefault(end, []).append(
            ((0, -start, index), f"[[/e{index}]]")
        )

    rendered = []
    for offset in range(len(text) + 1):
        rendered.extend(marker for _, marker in sorted(events.get(offset, [])))
        if offset < len(text):
            rendered.append(text[offset])
    return "".join(rendered)


def relation_label_map(record: SentenceRecord) -> dict[tuple[int, int, int, int], str]:
    labels: dict[tuple[int, int, int, int], set[str]] = {}
    for relation in record.relations:
        key = (
            relation.subject_start,
            relation.subject_end,
            relation.object_start,
            relation.object_end,
        )
        labels.setdefault(key, set()).add(relation.label)
        if relation.label in SYMMETRIC_RELATIONS:
            reverse = (key[2], key[3], key[0], key[1])
            labels.setdefault(reverse, set()).add(relation.label)
    return {
        key: min(values, key=RELATION_ORDER.__getitem__)
        for key, values in labels.items()
    }


def build_pair_examples(records: list[SentenceRecord]) -> tuple[list[PairExample], dict[tuple[str, str], list[int]]]:
    examples: list[PairExample] = []
    by_signature: dict[tuple[str, str], list[int]] = {}
    for record_index, record in enumerate(records):
        labels = relation_label_map(record)
        for subject_index, subject in enumerate(record.entities):
            for object_index, object_ in enumerate(record.entities):
                if subject_index == object_index:
                    continue
                key = (subject.start, subject.end, object_.start, object_.end)
                example = PairExample(
                    record_index=record_index,
                    subject=subject,
                    object=object_,
                    label=labels.get(key, "NIL"),
                )
                index = len(examples)
                examples.append(example)
                by_signature.setdefault((subject.type, object_.type), []).append(index)
    return examples, by_signature


def compute_similarities(
    training: list[SentenceRecord],
    targets: list[SentenceRecord],
    model_name: str,
    device: str,
    batch_size: int,
) -> Any:
    try:
        from sentence_transformers import SentenceTransformer
    except ImportError as error:
        raise RuntimeError(
            "sentence-transformers is required; use paper_llm/run_john_qwen.sh"
        ) from error

    model = SentenceTransformer(model_name, device=device)
    training_embeddings = model.encode(
        [record.text for record in training],
        batch_size=batch_size,
        show_progress_bar=True,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )
    target_embeddings = model.encode(
        [record.text for record in targets],
        batch_size=batch_size,
        show_progress_bar=True,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )
    return target_embeddings @ training_embeddings.T


def select_ner_examples(
    records: list[SentenceRecord], scores: Any, k: int, pool_size: int
) -> list[int]:
    ranked = sorted(
        range(len(records)),
        key=lambda index: (-float(scores[index]), records[index].doc_id, records[index].sentence_id),
    )
    remaining = ranked[: max(k, min(pool_size, len(ranked)))]
    selected: list[int] = []
    covered: set[str] = set()
    while remaining and len(selected) < k:
        best = min(
            remaining,
            key=lambda index: (
                -len(records[index].labels - covered),
                -float(scores[index]),
                records[index].doc_id,
                records[index].sentence_id,
            ),
        )
        selected.append(best)
        covered.update(records[best].labels)
        remaining.remove(best)
    return selected


def select_re_examples(
    subject: Entity,
    object_: Entity,
    examples: list[PairExample],
    by_signature: dict[tuple[str, str], list[int]],
    records: list[SentenceRecord],
    scores: Any,
    k: int,
    pool_size: int,
) -> list[PairExample]:
    if not examples:
        raise RuntimeError("training data contains no ordered entity pair for an RE example")

    def rank_key(index: int) -> tuple[Any, ...]:
        example = examples[index]
        record = records[example.record_index]
        return (
            -float(scores[example.record_index]),
            record.doc_id,
            record.sentence_id,
            example.subject.start,
            example.subject.end,
            example.object.start,
            example.object.end,
            example.label,
        )

    preferred = sorted(by_signature.get((subject.type, object_.type), []), key=rank_key)
    ranked = preferred
    if len(ranked) < k:
        preferred_set = set(preferred)
        ranked.extend(
            index
            for index in sorted(range(len(examples)), key=rank_key)
            if index not in preferred_set
        )
    remaining = ranked[: max(k, min(pool_size, len(ranked)))]
    selected: list[int] = []
    covered: set[str] = set()
    while remaining and len(selected) < k:
        best = min(
            remaining,
            key=lambda index: (
                -(examples[index].label not in covered),
                *rank_key(index),
            ),
        )
        selected.append(best)
        covered.add(examples[best].label)
        remaining.remove(best)
    if len(selected) != k:
        raise RuntimeError(f"could select only {len(selected)} of {k} RE examples")
    return [examples[index] for index in selected]


def entity_definitions_text() -> str:
    return "\n".join(f"- `{label}`: {definition}." for label, definition in ENTITY_DEFINITIONS)


def relation_definitions_text() -> str:
    definitions = ["- `NIL`: no listed relation holds for this ordered pair."]
    definitions.extend(
        f"- `{label}`: {definition}." for label, definition in RELATION_DEFINITIONS
    )
    return "\n".join(definitions)


def optional_prompt_sections(full_article: str, examples: str) -> str:
    sections = []
    if full_article:
        sections.append(f"# Full Article Context\n\n{full_article}")
    if examples:
        sections.append(f"# Few-Shot Examples\n\n{examples}")
    if not sections:
        return ""
    return "\n" + "\n\n".join(sections) + "\n"


def render_template(template: str, replacements: dict[str, str]) -> str:
    rendered = template
    for placeholder, value in replacements.items():
        token = "{{" + placeholder + "}}"
        if rendered.count(token) != 1:
            raise RuntimeError(f"expected one {token} in prompt template")
        rendered = rendered.replace(token, value)
    if re.search(r"\{\{[A-Z_]+\}\}", rendered):
        raise RuntimeError("unfilled prompt-template placeholder")
    return rendered


def build_ner_prompt(
    target: SentenceRecord,
    examples: list[SentenceRecord],
    template: str,
    full_article_context: str = "",
    output_format: str = "indices",
) -> str:
    blocks = []
    for number, example in enumerate(examples, start=1):
        if output_format == "indices":
            output = {
                "entities": [
                    {"start": entity.start, "end": entity.end, "type": entity.type}
                    for entity in example.entities
                ]
            }
            blocks.append(
                f"## Example {number}\n\n"
                f"Input: {json.dumps(indexed_tokens(example), ensure_ascii=False)}\n\n"
                f"Output: {json.dumps(output, ensure_ascii=False)}"
            )
        elif output_format == "inline":
            blocks.append(
                f"## Example {number}\n\n"
                f"Input: {example.text}\n\n"
                f"Output: {inline_annotated_sentence(example)}"
            )
        else:
            raise ValueError(f"unknown NER output format: {output_format}")
    examples_text = "\n\n".join(blocks)
    main_input = (
        json.dumps(indexed_tokens(target), ensure_ascii=False)
        if output_format == "indices"
        else target.text
    )
    return render_template(
        template,
        {
            "LABEL_DEFINITIONS": entity_definitions_text(),
            "OPTIONAL_SECTIONS": optional_prompt_sections(
                full_article_context, examples_text
            ),
            "MAIN_INPUT": main_input,
        },
    )


def pair_input(record: SentenceRecord, subject: Entity, object_: Entity) -> dict[str, Any]:
    return {
        "sentence_tokens": indexed_tokens(record),
        "subject": entity_dict(subject, record),
        "object": entity_dict(object_, record),
    }


def build_re_prompt(
    target: SentenceRecord,
    subject: Entity,
    object_: Entity,
    examples: list[tuple[SentenceRecord, PairExample]],
    template: str,
    full_article_context: str = "",
) -> str:
    blocks = []
    for number, (example_record, example) in enumerate(examples, start=1):
        blocks.append(
            f"## Example {number}\n\n"
            f"Input: {json.dumps(pair_input(example_record, example.subject, example.object), ensure_ascii=False)}\n\n"
            f"Output: {json.dumps({'label': example.label})}"
        )
    examples_text = "\n\n".join(blocks)
    return render_template(
        template,
        {
            "LABEL_DEFINITIONS": relation_definitions_text(),
            "OPTIONAL_SECTIONS": optional_prompt_sections(
                full_article_context, examples_text
            ),
            "MAIN_INPUT": json.dumps(pair_input(target, subject, object_), ensure_ascii=False),
        },
    )


def api_json(
    base_url: str,
    path: str,
    payload: dict[str, Any] | None = None,
    timeout: int = 30,
) -> dict[str, Any]:
    data = None
    headers = {"Accept": "application/json"}
    method = "GET"
    if payload is not None:
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        headers["Content-Type"] = "application/json"
        method = "POST"
    request = urllib.request.Request(
        f"{base_url.rstrip('/')}{path}", data=data, headers=headers, method=method
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"Ollama HTTP {error.code} for {path}: {detail}") from error
    except urllib.error.URLError as error:
        raise RuntimeError(f"cannot reach Ollama at {base_url}: {error.reason}") from error


def response_metrics(response: dict[str, Any]) -> dict[str, Any]:
    result = {
        key: response.get(key)
        for key in (
            "created_at",
            "done",
            "done_reason",
            "total_duration",
            "load_duration",
            "prompt_eval_count",
            "prompt_eval_duration",
            "eval_count",
            "eval_duration",
        )
        if response.get(key) is not None
    }
    count = response.get("eval_count")
    duration = response.get("eval_duration")
    if isinstance(count, int) and isinstance(duration, int) and duration > 0:
        result["generation_tokens_per_second"] = round(
            count / (duration / 1_000_000_000), 3
        )
    return result


def parse_json_content(response: dict[str, Any]) -> tuple[str, Any, str | None]:
    message = response.get("message")
    if not isinstance(message, dict) or not isinstance(message.get("content"), str):
        return "", None, "response has no string message.content"
    content = message["content"].strip()
    try:
        return content, json.loads(content), None
    except json.JSONDecodeError as error:
        return content, None, str(error)


def parse_inline_ner(content: str, tokens: tuple[str, ...]) -> tuple[list[Entity], list[str]]:
    expected_text, token_spans = detokenize_with_spans(tokens)
    plain_parts = []
    plain_offset = 0
    source_offset = 0
    active: dict[str, tuple[int, str]] = {}
    used_ids: set[str] = set()
    completed: list[tuple[int, int, str, str]] = []
    warnings: list[str] = []

    for marker in INLINE_MARKER_RE.finditer(content):
        chunk = content[source_offset : marker.start()]
        plain_parts.append(chunk)
        plain_offset += sum(not character.isspace() for character in chunk)
        source_offset = marker.end()

        close_id = marker.group("close_id")
        if close_id is not None:
            opened = active.pop(close_id, None)
            if opened is None:
                warnings.append(f"closing marker for unopened {close_id}; ignored")
                continue
            start, label = opened
            completed.append((start, plain_offset, label, close_id))
            continue

        open_id = marker.group("open_id")
        if open_id in used_ids:
            warnings.append(f"duplicate marker id {open_id}; later opening ignored")
            continue
        used_ids.add(open_id)
        active[open_id] = (plain_offset, marker.group("label"))

    plain_parts.append(content[source_offset:])
    plain_text = "".join(plain_parts)
    compact_plain = "".join(character for character in plain_text if not character.isspace())
    compact_expected = "".join(
        character for character in expected_text if not character.isspace()
    )
    if compact_plain != compact_expected:
        return [], [
            "text outside inline markers differs from the input sentence beyond "
            "whitespace; all entities ignored",
            *warnings,
        ]

    for marker_id in sorted(active):
        warnings.append(f"unclosed marker {marker_id}; ignored")

    compact_offsets = [0]
    for character in expected_text:
        compact_offsets.append(compact_offsets[-1] + int(not character.isspace()))
    starts = {
        compact_offsets[start]: index for index, (start, _) in enumerate(token_spans)
    }
    ends = {
        compact_offsets[end]: index for index, (_, end) in enumerate(token_spans)
    }
    entities = []
    seen: set[tuple[int, int]] = set()
    for char_start, char_end, label, marker_id in sorted(
        completed,
        key=lambda row: (
            row[0],
            row[1],
            ENTITY_ORDER.get(row[2], len(ENTITY_ORDER)),
            row[3],
        ),
    ):
        if label not in ENTITY_ORDER:
            warnings.append(f"marker {marker_id} has unknown type {label!r}; ignored")
            continue
        if char_start not in starts or char_end not in ends:
            warnings.append(f"marker {marker_id} does not align to token boundaries; ignored")
            continue
        start, end = starts[char_start], ends[char_end]
        if start > end:
            warnings.append(f"marker {marker_id} is empty or reversed; ignored")
            continue
        if (start, end) in seen:
            warnings.append(f"duplicate span ({start}, {end}); later prediction ignored")
            continue
        seen.add((start, end))
        entities.append(Entity(start, end, label))
    return entities, warnings


def sanitize_ner(payload: Any, token_count: int) -> tuple[list[Entity], list[str]]:
    warnings: list[str] = []
    rows = payload.get("entities") if isinstance(payload, dict) else None
    if not isinstance(rows, list):
        return [], ["NER response has no entities array; treated as empty"]
    entities: list[Entity] = []
    seen: set[tuple[int, int]] = set()
    for index, row in enumerate(rows):
        if not isinstance(row, dict):
            warnings.append(f"entities[{index}] is not an object; ignored")
            continue
        start, end, label = row.get("start"), row.get("end"), row.get("type")
        if isinstance(start, bool) or isinstance(end, bool):
            warnings.append(f"entities[{index}] uses boolean coordinates; ignored")
            continue
        if not isinstance(start, int) or not isinstance(end, int):
            warnings.append(f"entities[{index}] has non-integer coordinates; ignored")
            continue
        if label not in ENTITY_ORDER:
            warnings.append(f"entities[{index}] has unknown type {label!r}; ignored")
            continue
        if not 0 <= start <= end < token_count:
            warnings.append(f"entities[{index}] span ({start}, {end}) is out of range; ignored")
            continue
        if (start, end) in seen:
            warnings.append(f"duplicate span ({start}, {end}); later prediction ignored")
            continue
        seen.add((start, end))
        entities.append(Entity(start, end, label))
    entities.sort(key=lambda entity: (entity.start, entity.end, ENTITY_ORDER[entity.type]))
    return entities, warnings


def sanitize_re(payload: Any) -> tuple[str, list[str]]:
    label = payload.get("label") if isinstance(payload, dict) else None
    if label == "NIL" or label in RELATION_ORDER:
        return label, []
    return "NIL", [f"unknown or missing relation label {label!r}; treated as NIL"]


def load_trace(path: Path) -> dict[str, dict[str, Any]]:
    events: dict[str, dict[str, Any]] = {}
    if not path.exists():
        return events
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, start=1):
            if not line.strip():
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError as error:
                raise RuntimeError(f"invalid trace JSON on line {line_number}: {error}") from error
            if isinstance(event, dict) and isinstance(event.get("key"), str):
                events[event["key"]] = event
    return events


def append_trace(path: Path, event: dict[str, Any]) -> None:
    with path.open("a", encoding="utf-8") as stream:
        stream.write(json.dumps(event, ensure_ascii=False, sort_keys=True) + "\n")
        stream.flush()
        os.fsync(stream.fileno())


def ollama_call(
    *,
    key: str,
    stage: str,
    prompt: str,
    args: argparse.Namespace,
    trace_path: Path,
    trace: dict[str, dict[str, Any]],
    metadata: dict[str, Any],
    ner_tokens: tuple[str, ...] | None = None,
) -> tuple[Any, bool]:
    prompt_hash = sha256_bytes(prompt.encode("utf-8"))
    previous = trace.get(key)
    if previous is not None:
        if previous.get("prompt_sha256") != prompt_hash:
            raise RuntimeError(f"resume prompt changed for {key}; use a fresh output directory")
        if bool(previous.get("think", False)) != args.think:
            raise RuntimeError(f"resume thinking mode changed for {key}; use a fresh output directory")
        if stage == "ner" and previous.get("ner_output_format", "indices") != args.ner_output_format:
            raise RuntimeError(f"resume NER output format changed for {key}; use a fresh output directory")
        return previous.get("prediction"), True

    num_predict = args.ner_num_predict if stage == "ner" else args.re_num_predict
    payload = {
        "model": args.model,
        "messages": [{"role": "user", "content": prompt}],
        "stream": False,
        "think": args.think,
        "keep_alive": args.keep_alive,
        "options": {
            "temperature": 0.0,
            "num_ctx": args.num_ctx,
            "num_predict": num_predict,
        },
    }
    if stage == "re" or args.ner_output_format == "indices":
        payload["format"] = "json"
    wall_start = time.monotonic()
    response = api_json(args.base_url, "/api/chat", payload=payload, timeout=args.timeout)
    wall_seconds = time.monotonic() - wall_start
    parse_error = None
    if stage == "ner" and args.ner_output_format == "inline":
        message = response.get("message")
        if not isinstance(message, dict) or not isinstance(message.get("content"), str):
            content = ""
            prediction = []
            warnings = ["response has no string message.content"]
        else:
            content = message["content"].strip()
            if ner_tokens is None:
                raise RuntimeError("inline NER parsing requires the input tokens")
            prediction, warnings = parse_inline_ner(content, ner_tokens)
    else:
        content, parsed, parse_error = parse_json_content(response)
        if stage == "ner":
            prediction, warnings = sanitize_ner(parsed, metadata["token_count"])
        else:
            prediction, warnings = sanitize_re(parsed)

    if stage == "ner":
        serialized_prediction: Any = [
            {"start": entity.start, "end": entity.end, "type": entity.type}
            for entity in prediction
        ]
    else:
        serialized_prediction = prediction
    if parse_error:
        warnings.insert(0, f"invalid JSON: {parse_error}")

    event = {
        "key": key,
        "stage": stage,
        "recorded_at": utc_now(),
        "prompt_sha256": prompt_hash,
        "prompt": prompt,
        "raw_response": content,
        "think": args.think,
        "prediction": serialized_prediction,
        "warnings": warnings,
        "wall_seconds": round(wall_seconds, 6),
        "ollama_metrics": response_metrics(response),
        **metadata,
    }
    message = response.get("message")
    if isinstance(message, dict) and isinstance(message.get("thinking"), str):
        event["raw_thinking"] = message["thinking"]
    if stage == "ner":
        event["ner_output_format"] = args.ner_output_format
    append_trace(trace_path, event)
    trace[key] = event
    return serialized_prediction, False


def git_commit(repo_root: Path) -> str | None:
    completed = subprocess.run(
        ["git", "-C", str(repo_root), "rev-parse", "HEAD"],
        check=False,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip() if completed.returncode == 0 else None


def gpu_inventory() -> list[str]:
    try:
        completed = subprocess.run(
            [
                "nvidia-smi",
                "--query-gpu=name,uuid,memory.total,driver_version",
                "--format=csv,noheader",
            ],
            check=False,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        return []
    if completed.returncode != 0:
        return []
    return [line.strip() for line in completed.stdout.splitlines() if line.strip()]


def package_version(name: str) -> str | None:
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
        return None


def model_record(tags: dict[str, Any], requested_model: str) -> dict[str, Any] | None:
    aliases = {requested_model, f"{requested_model}:latest"}
    if ":" not in requested_model:
        aliases.add(f"{requested_model}:latest")
    for model in tags.get("models", []):
        if aliases & {model.get("name"), model.get("model")}:
            return {
                key: model.get(key)
                for key in ("name", "model", "digest", "size", "modified_at", "details")
                if model.get(key) is not None
            }
    return None


