    parser.add_argument("--retriever", default=DEFAULT_RETRIEVER)
    parser.add_argument("--retriever-device", default="cpu")
    parser.add_argument("--embedding-batch-size", type=int, default=64)
    parser.add_argument("--ner-shots", type=int, default=10)
    parser.add_argument("--re-shots", type=int, default=1)
    parser.add_argument("--retrieval-pool-size", type=int, default=100)
    parser.add_argument("--num-ctx", type=int, default=32768)
    parser.add_argument("--ner-num-predict", type=int, default=2048)
    parser.add_argument("--re-num-predict", type=int, default=64)
    parser.add_argument("--keep-alive", default="30m")
    parser.add_argument("--timeout", type=int, default=3600)
    parser.add_argument("--think", action="store_true")
    parser.add_argument(
        "--full-article-context",
        action="store_true",
        help="include the full target article before the few-shot examples",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=script_dir / "results" / "qwen3.8-27b-ollama-john-00016_2106_09462",
    )
